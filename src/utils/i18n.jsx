const LanguageContext = createContext({
  language: 'en',
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
  supportedLanguages: SUPPORTED_LANGUAGES
});

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = localStorage.getItem('driverhub_language');
      if (saved && translations[saved]) return saved;
      // map legacy 'English', 'Spanish', etc.
      if (saved === 'Spanish') return 'es';
      if (saved === 'German') return 'de';
      if (saved === 'Russian') return 'ru';
      if (saved === 'Chinese') return 'zh';
      if (saved === 'Portuguese') return 'pt';
      if (saved === 'French') return 'fr';
      if (saved === 'Indonesian') return 'id';
      if (saved === 'Turkish') return 'tr';
      if (saved === 'Vietnamese') return 'vi';
      return 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (newLang) => {
    let code = newLang;
    if (newLang === 'English') code = 'en';
    else if (newLang === 'Spanish') code = 'es';
    else if (newLang === 'German') code = 'de';
    else if (newLang === 'Russian') code = 'ru';
    else if (newLang === 'Chinese') code = 'zh';
    else if (newLang === 'Portuguese') code = 'pt';
    else if (newLang === 'French') code = 'fr';
    else if (newLang === 'Indonesian') code = 'id';
    else if (newLang === 'Turkish') code = 'tr';
    else if (newLang === 'Vietnamese') code = 'vi';

    if (!translations[code]) code = 'en';

    setLanguageState(code);
    try {
      localStorage.setItem('driverhub_language', code);
    } catch {}

    if (window.electronAPI?.saveSettings) {
      window.electronAPI.saveSettings({ language: code });
    }
  };

  useEffect(() => {
    const fetchSavedLanguage = async () => {
      try {
        if (window.electronAPI?.getSettings) {
          const s = await window.electronAPI.getSettings();
          if (s?.language) {
            let code = s.language;
            if (code === 'English') code = 'en';
            else if (code === 'Spanish') code = 'es';
            else if (code === 'German') code = 'de';
            else if (code === 'Russian') code = 'ru';
            else if (code === 'Chinese') code = 'zh';
            else if (code === 'Portuguese') code = 'pt';
            else if (code === 'French') code = 'fr';
            else if (code === 'Indonesian') code = 'id';
            else if (code === 'Turkish') code = 'tr';
            else if (code === 'Vietnamese') code = 'vi';

            if (translations[code]) {
              setLanguageState(code);
              try { localStorage.setItem('driverhub_language', code); } catch {}
            }
          }
        }
      } catch {}
    };
    fetchSavedLanguage();
  }, []);

  const t = (key, fallback) => {
    const langDict = translations[language] || translations['en'];
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    const enDict = translations['en'];
    if (enDict && enDict[key] !== undefined) {
      return enDict[key];
    }
    return fallback !== undefined ? fallback : key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, supportedLanguages: SUPPORTED_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
